"""Engine/call/reader Spanish UI boundaries, including language round-trip.
Synthetic browser contexts: no microphone, model download or cloud call required.
uv run --with playwright python tests/engine-call-locale-regression.py URL
"""
import sys
from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,args=['--no-sandbox'])
    for width in [390,1280]:
        ctx=browser.new_context(viewport={'width':width,'height':900},service_workers='block')
        page=ctx.new_page();errors=[]
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.add_init_script("""const d=new Date();localStorage.setItem('bibley_today_seen_v1',d.getFullYear()+'-'+String(d.getMonth()+1).padStart(2,'0')+'-'+String(d.getDate()).padStart(2,'0'));localStorage.setItem('bibley_seen_version','7.1');navigator.mediaDevices.getUserMedia=()=>Promise.reject(Object.assign(new Error('synthetic denial'),{name:'NotAllowedError'}));""")
        page.goto(sys.argv[1],wait_until='domcontentloaded')
        page.wait_for_function('!!window.BibleyLocale && !!window.BibleyCall && !!window.BibleyLocalAI && !!window.BibleySettings')
        verses=page.locator('.pane[data-pane=a] .verses-text span[data-verse]')
        verses.first.wait_for(timeout=30000);original=verses.all_text_contents()
        page.evaluate("BibleyLocale.set('es');BibleySettings.open('aiengine')")
        root=page.locator('.bs-root')
        expect(root.locator('[data-seg=mode] [data-v=local]')).to_have_text('IA en el dispositivo')
        root.locator('[data-seg=mode] [data-v=local]').click()
        expect(root.locator('.ai-mname').first).to_contain_text('Modelo 1: Bibley 2.1')
        expect(root.locator('[data-act="dl-qwen3-0.6b"]')).to_have_text('Descargar y cargar')
        expect(root.locator('.ai-mdesc').first).to_contain_text('Respuestas rápidas')
        expect(root.locator('.ai-mst').first).to_have_text('Aún no se ha descargado')
        expect(root.locator('.ai-caps')).to_contain_text('Detectado:')
        page.screenshot(path=f'/tmp/bibley-engine-es-{width}.png')
        page.evaluate("""()=>{BibleyLocalAI.status=()=>({state:'ready',model:'qwen3-0.6b',backend:'cpu'});BibleySettings.open('aiengine')}""")
        expect(root.locator('.ai-mst').first).to_have_text('✓ Cargado en memoria y listo (CPU)')
        page.evaluate("""()=>{BibleyLocalAI.status=()=>({state:'loading',model:'qwen3-0.6b',percent:23,text:'Downloading Bibley 2.1 (Qwen3 0.6B)... 10 of 40 MB'});BibleySettings.open('aiengine')}""")
        expect(root.locator('.ai-mst').first).to_have_text('Descargando Bibley 2.1 (Qwen3 0.6B)... 10 de 40 MB (23%)')
        page.evaluate("BibleyLocale.set('en')")
        expect(root.locator('.ai-mst').first).to_have_text('Downloading Bibley 2.1 (Qwen3 0.6B)... 10 of 40 MB (23%)')
        page.evaluate("BibleyLocale.set('es')")
        # No model network request: fake only state/capability APIs, restore on reload.
        page.evaluate("""()=>{const L=BibleyLocalAI;L.status=()=>({state:'error',model:'qwen3-0.6b',error:'provider sentinel <script>no</script>'});BibleySettings.open('aiengine')}""")
        expect(root.locator('.ai-mst').first).to_have_text('No se pudo cargar: provider sentinel <script>no</script>')
        assert root.locator('.ai-mst script').count()==0
        page.evaluate("BibleyLocale.set('en')")
        expect(root.locator('.ai-mst').first).to_have_text("Couldn't load: provider sentinel <script>no</script>")
        expect(root.locator('[data-act="dl-qwen3-0.6b"]')).to_have_text('Download & Load')
        page.evaluate("BibleySettings.close();BibleyLocale.set('es');BibleyLocalAI.openSwitcher()")
        expect(page.locator('#laiMenu [data-v=cloud]')).to_contain_text('IA en la nube')
        expect(page.locator('#laiMenu [data-v=settings]')).to_contain_text('Ajustes del motor de IA')
        page.evaluate("BibleyLocale.set('en')")
        expect(page.locator('#laiMenu [data-v=cloud]')).to_contain_text('Cloud AI')
        page.evaluate("BibleyLocale.set('es')")
        expect(page.locator('#laiMenu [data-v=settings]')).to_contain_text('Ajustes del motor de IA')
        page.reload(wait_until='domcontentloaded');page.wait_for_function('!!window.BibleyCall && !!window.BibleyLocale')
        page.evaluate("BibleyLocale.set('es');BibleyCall.open()")
        expect(page.locator('#bcState')).to_have_text('El micrófono está desactivado')
        expect(page.locator('#bcRetry')).to_have_text('Intentar de nuevo')
        expect(page.locator('#bcMsg')).to_contain_text('Bibley necesita el micrófono')
        expect(page.locator('#bcEnd')).to_have_attribute('aria-label','Colgar')
        page.screenshot(path=f'/tmp/bibley-call-es-{width}.png')
        page.locator('#bcMute').click()
        expect(page.locator('#bcMute')).to_have_attribute('aria-label','Activar micrófono')
        # Captions must never be translated, even if content is an exact UI key.
        page.evaluate("""()=>{const d=document.createElement('div');d.innerHTML='<span class="bc-who">You</span><span class="bc-txt">Close</span>';document.querySelector('#bcCaps').append(d)}""")
        expect(page.locator('.bc-who')).to_have_text('Tú')
        expect(page.locator('.bc-txt')).to_have_text('Close')
        page.evaluate("BibleyLocale.set('en')")
        expect(page.locator('#bcState')).to_have_text('Microphone is off')
        expect(page.locator('#bcEnd')).to_have_attribute('aria-label','Hang up')
        expect(page.locator('.bc-who')).to_have_text('You')
        page.evaluate("BibleyCall.hangUp();BibleyLocale.set('es')")
        verses.first.click()
        expect(page.locator('.fx-selbar .t b')).to_have_text('1 versículo seleccionado')
        expect(page.locator('.fx-selbar [data-a=bm]')).to_contain_text('Marcador')
        expect(page.locator('.fx-selbar [data-a=ai]')).to_contain_text('Explicar')
        expect(page.locator('.fx-selbar [data-c=yellow]')).to_have_attribute('aria-label','Resaltado amarillo')
        page.evaluate("document.querySelector('.fx-selbar-x').click();document.querySelector('#openNavBtn').click()")
        expect(page.locator('#drawer .drawer-head .title')).to_contain_text('Libros')
        expect(page.locator('#drawer .drawer-head small')).to_have_text('Leyendo Genesis 1')
        page.wait_for_function("Math.abs(document.querySelector('#drawer').getBoundingClientRect().left)<1")
        page.screenshot(path=f'/tmp/bibley-engine-call-reader-es-{width}.png')
        page.evaluate("BibleyLocale.set('en')")
        expect(page.locator('#drawer .drawer-head small')).to_have_text('Reading Genesis 1')
        assert verses.all_text_contents()==original
        assert not errors, errors
        ctx.close();print(f'{width}px: engine, call, reader locale/boundaries passed')
    browser.close()
