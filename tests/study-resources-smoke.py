"""Run with: uv run --with playwright python tests/study-resources-smoke.py URL"""
import re
import sys
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, args=['--no-sandbox'])
    page = browser.new_page(viewport={'width':390,'height':844})
    issues = []
    page.on('pageerror', lambda err: issues.append(str(err)))
    page.add_init_script("""const d=new Date(); localStorage.setItem('bibley_today_seen_v1',d.getFullYear()+'-'+String(d.getMonth()+1).padStart(2,'0')+'-'+String(d.getDate()).padStart(2,'0')); localStorage.setItem('bibley_seen_version','7.1');""")
    page.goto(sys.argv[1], wait_until='domcontentloaded')
    page.wait_for_function('!!window.BibleyTools?.openVerseWords')
    sheet = page.locator('.fx-sheet.open')
    close = lambda: sheet.get_by_role('button',name='Close',exact=True).click()
    reader = page.locator('.pane[data-pane=a]')
    page.evaluate('BibleyCore.goTo(42,3)')
    v16 = reader.locator('[data-verse="16"]'); v16.wait_for(timeout=30000)
    text = v16.inner_text()
    reader.get_by_role('button',name='Red letters',exact=True).click()
    expect(v16.locator('.bp-jesus').first).to_contain_text('For God so loved the world')
    assert v16.inner_text() == text
    reader.get_by_role('button',name='Red letters',exact=True).click()
    expect(page.locator('html')).not_to_have_class(re.compile(r'bp-red-letters'))
    v16.click(); page.get_by_role('button',name='Original words',exact=True).click()
    sheet.get_by_text('God · G2316',exact=True).first.click()
    expect(sheet.get_by_text(re.compile(r'θεός.*the[oó]s')).first).to_be_visible()
    sheet.get_by_role('button',name='Hebrew & Greek interlinear',exact=True).click()
    words = sheet.get_by_role('list',name='Interlinear words')
    expect(words).to_have_attribute('dir','ltr')
    expect(words.get_by_role('listitem').first).to_contain_text('οὕτως')
    expect(words.get_by_role('listitem').first).to_contain_text('houtōs')
    expect(words.get_by_role('listitem').first).to_contain_text('Thus')
    expect(words.get_by_text('G2316 · N-NSM-T',exact=True).first).to_be_visible()
    sheet.get_by_role('button',name='← Back',exact=True).click()
    expect(sheet.get_by_role('region',name='World English Bible tags')).to_be_visible(); close()
    v16.click(); page.get_by_role('button',name='Linked verses',exact=True).click()
    expect(sheet.get_by_text('Related passages · OpenBible.info')).to_be_visible()
    assert sheet.locator('.bp-card button').count() >= 5; close()
    def tool(button):
        page.evaluate('BibleyCore.openAi("explore")')
        page.get_by_role('button',name=button,exact=True).click()
    tool('Bible dictionary'); sheet.get_by_role('searchbox').fill('Nicodemus')
    expect(sheet.locator('summary').filter(has_text='Nicodemus').first).to_be_visible(); close()
    tool('Bible timeline'); sheet.get_by_role('searchbox').fill('Creation of all things')
    expect(sheet.locator('summary').filter(has_text='Creation of all things').first).to_be_visible(); close()
    tool('Character profiles'); sheet.get_by_role('searchbox').fill('Aaron')
    expect(sheet.locator('summary').filter(has_text='Aaron').first).to_be_visible(); close()
    tool('Bible places map'); sheet.get_by_role('searchbox').fill('Jerusalem')
    sheet.get_by_role('button',name='Jerusalem',exact=True).click()
    sheet.get_by_role('button',name=re.compile('^Map: ')).first.click()
    expect(sheet.locator('iframe')).to_have_attribute('src',re.compile(r'openstreetmap.org/export/embed.html.*marker=')); close()
    tool('Commentaries & outline'); sheet.get_by_text('Book outline · chapter headings',exact=True).click()
    expect(sheet.get_by_role('button',name='Chapter 3',exact=True)).to_be_visible()
    expect(sheet.get_by_text('Book introduction',exact=True)).to_be_visible(timeout=20000)
    expect(sheet.get_by_text('Verse 1',exact=True).first).to_be_visible()
    sheet.get_by_label('Commentary source').select_option('jamieson-fausset-brown')
    expect(sheet.get_by_text('came to Jesus by night--One of those superficial',exact=False).first).to_be_visible(); close()
    page.evaluate('BibleyCore.goTo(0,1)')
    reader.locator('[data-verse="1"]').click()
    page.get_by_role('button',name='Original words',exact=True).click()
    sheet.get_by_role('button',name='Hebrew & Greek interlinear',exact=True).click()
    expect(words).to_have_attribute('dir','rtl')
    expect(words.get_by_role('listitem').first).to_contain_text('be./re.Shit')
    expect(words.get_by_role('listitem').first).to_contain_text('H7225'); close()
    page.evaluate('BibleyCore.goTo(42,3)')
    expect(v16).to_contain_text('For God so loved the world')
    page.evaluate('BibleySettings.open()')
    page.get_by_role('button',name='Language / Idioma English / Español').click()
    page.locator('.bs-page select').select_option('es')
    expect(page.locator('#openNavBtn')).to_have_text('Libros')
    expect(page.locator('.fx-dock button[data-a=today]')).to_have_attribute('aria-label','Hoy')
    page.locator('.bs-page select').select_option('en')
    expect(page.locator('#openNavBtn')).to_have_text('Books')
    page.locator('.bs-page select').select_option('es')
    page.reload(wait_until='domcontentloaded')
    expect(page.locator('#openNavBtn')).to_have_text('Libros')
    expect(reader.locator('[data-verse="16"]')).to_contain_text('For God so loved the world')
    page.locator('.fx-dock button[data-a=today]').click()
    sheet.get_by_role('button',name='Resumen diario',exact=True).click()
    expect(sheet.locator('.fx-sheet-title')).to_have_text('Resumen diario')
    expect(sheet.get_by_role('button',name='Copiar resumen como texto',exact=True)).to_be_visible()
    sheet.get_by_role('button',name='‹ Anterior',exact=True).click()
    expect(sheet.get_by_text('No hay actividad registrada para este día.',exact=False)).to_be_visible()
    sheet.get_by_role('button',name='← Atrás',exact=True).click()
    sheet.get_by_role('button',name='Resumen mensual',exact=True).click()
    expect(sheet.get_by_text('capítulos leídos',exact=True)).to_be_visible()
    expect(sheet.get_by_text('(hasta ahora)',exact=False)).to_be_visible()
    assert not issues, issues
    browser.close()
    print('PASS: red-letter toggle unchanged text; tagged Greek, source-order Hebrew/Greek interlinear; John cross-references; Easton dictionary; timeline, profiles, map embedding; sourced outlines and commentaries; Spanish navigation persistence')
